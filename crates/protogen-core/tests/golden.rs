//! 黄金测试：用 `tests/golden/` 下的真实样本验证输出一致性。
//!
//! 两层验证：
//! 1. `expected.pb.h/.c` —— nanopb 0.3.9.1 的原始输出（无注释），验证生成器本身
//! 2. `expected_notes.pb.h` —— C# 旧工具注入注释后的输出，验证注释同步

use std::path::{Path, PathBuf};

use protogen_core::gen::{comments_inject, render};
use protogen_core::{options, parse};

fn golden_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../tests/golden")
        .canonicalize()
        .expect("找不到 tests/golden 目录")
}

struct Case {
    name: String,
    dir: PathBuf,
    proto: PathBuf,
}

fn collect_cases() -> Vec<Case> {
    let root = golden_dir();
    let mut cases = Vec::new();
    let mut entries: Vec<_> = std::fs::read_dir(&root)
        .expect("读取 golden 目录失败")
        .filter_map(|e| e.ok())
        .collect();
    entries.sort_by_key(|e| e.path());

    for entry in entries {
        let dir = entry.path();
        if !dir.is_dir() {
            continue;
        }
        let Some(proto) = std::fs::read_dir(&dir)
            .ok()
            .and_then(|rd| {
                rd.filter_map(|e| e.ok())
                    .map(|e| e.path())
                    .find(|p| p.extension().map(|x| x == "proto").unwrap_or(false))
            })
        else {
            continue;
        };
        let name = dir
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or_default()
            .to_string();
        cases.push(Case {
            name,
            dir: dir.clone(),
            proto,
        });
    }
    cases
}

fn normalize(s: &str) -> String {
    // 时间戳行不参与比对
    s.lines()
        .filter(|l| !l.starts_with("/* Generated by"))
        .collect::<Vec<_>>()
        .join("\n")
}

fn gen_options_for(proto: &Path) -> parse::OptionsMap {
    let opt_path = proto.with_extension("options");
    if opt_path.exists() {
        parse::read_options_file(&opt_path).unwrap_or_default()
    } else {
        Default::default()
    }
}

#[test]
fn golden_nanopb_output_matches() {
    let cases = collect_cases();
    assert!(!cases.is_empty(), "没有找到任何黄金样本");

    let mut failures = Vec::new();
    let mut checked = 0;

    for case in &cases {
        let opts = gen_options_for(&case.proto);
        let file = match parse::parse_proto(&case.proto, &[], &opts) {
            Ok(f) => f,
            Err(e) => {
                failures.push(format!("{}: 解析失败 {}", case.name, e));
                continue;
            }
        };
        let gen_opts = render::GenOptions::default();
        let out = render::generate(&file, &gen_opts);

        for (ext, actual) in [("h", &out.header), ("c", &out.source)] {
            let expected_path = case.dir.join(format!("expected.pb.{}", ext));
            if !expected_path.exists() {
                continue;
            }
            checked += 1;
            let expected = std::fs::read_to_string(&expected_path).unwrap();
            if normalize(actual) != normalize(&expected) {
                failures.push(format!(
                    "{} .pb.{} 不一致{}",
                    case.name,
                    ext,
                    first_diff(actual, &expected)
                ));
            }
        }
    }

    assert!(checked > 0, "没有比对任何文件");
    assert!(
        failures.is_empty(),
        "\n{} 个文件比对失败:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

#[test]
fn golden_notes_injection_matches_csharp() {
    let cases = collect_cases();
    let mut failures = Vec::new();
    let mut checked = 0;

    for case in &cases {
        let expected_path = case.dir.join("expected_notes.pb.h");
        if !expected_path.exists() {
            continue;
        }
        checked += 1;

        let opts = gen_options_for(&case.proto);
        let file = match parse::parse_proto(&case.proto, &[], &opts) {
            Ok(f) => f,
            Err(e) => {
                failures.push(format!("{}: 解析失败 {}", case.name, e));
                continue;
            }
        };

        let out = render::generate(&file, &render::GenOptions::default());
        let injected = comments_inject::inject(&file, &out.header);
        let aligned = comments_inject::format_enum(&injected);

        let expected = std::fs::read_to_string(&expected_path).unwrap();
        if normalize(&aligned) != normalize(&expected) {
            failures.push(format!(
                "{} 注释注入不一致{}",
                case.name,
                first_diff(&aligned, &expected)
            ));
        }
    }

    assert!(checked > 0, "没有可比对的注释样本");
    assert!(
        failures.is_empty(),
        "\n{} 个样本注释注入失败:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

#[test]
fn golden_options_generation_matches() {
    let cases = collect_cases();
    let mut failures = Vec::new();
    let mut checked = 0;

    for case in &cases {
        let expected_path = case.dir.join("expected.options");
        if !expected_path.exists() {
            continue;
        }
        checked += 1;

        let file = match parse::parse_proto(&case.proto, &[], &Default::default()) {
            Ok(f) => f,
            Err(e) => {
                failures.push(format!("{}: 解析失败 {}", case.name, e));
                continue;
            }
        };
        let actual = options::generate_options(&file);
        let expected = std::fs::read_to_string(&expected_path).unwrap();
        let expected = expected.replace("\r\n", "\n");
        if actual.trim_end() != expected.trim_end() {
            failures.push(format!("{} options 不一致", case.name));
        }
    }

    assert!(checked > 0, "没有可比对的 options 样本");
    assert!(failures.is_empty(), "\n{}", failures.join("\n"));
}

/// 找出第一处差异，方便定位
fn first_diff(actual: &str, expected: &str) -> String {
    let a: Vec<&str> = actual.lines().collect();
    let e: Vec<&str> = expected.lines().collect();
    for i in 0..a.len().max(e.len()) {
        let al = a.get(i).copied().unwrap_or("<缺失>");
        let el = e.get(i).copied().unwrap_or("<缺失>");
        if al != el {
            return format!(
                "\n  第 {} 行:\n    实际: {:?}\n    期望: {:?}",
                i + 1,
                al,
                el
            );
        }
    }
    String::new()
}
