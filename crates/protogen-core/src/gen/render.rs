fn gen_source(file: &ProtoFile, opts: &GenOptions) -> String {
    let mut out = String::new();

    out.push_str("/* Automatically generated nanopb constant definitions */\n");
    if opts.no_timestamp {
        out.push_str(&format!("/* Generated by {} */\n\n", opts.nanopb_version));
    } else {
        out.push_str(&format!(
            "/* Generated by {} at {}. */\n\n",
            opts.nanopb_version, opts.timestamp
        ));
    }

    out.push_str(&format!("#include \"{}.pb.h\"\n", file.base_name));
    out.push('\n');
    out.push_str("/* @@protoc_insertion_point(includes) */\n");
    out.push_str("#if PB_PROTO_HEADER_VERSION != 30\n");
    out.push_str("#error Regenerate this file with the current version of nanopb generator.\n");
    out.push_str("#endif\n");
    out.push('\n');

    for m in &file.messages {
        for f in &m.fields {
            if let Some(d) = render_default_def(m, f) {
                out.push_str(&d);
                out.push('\n');
            }
        }
    }

    out.push_str("\n\n");

    for m in &file.messages {
        out.push_str(&render_fields_definition(m));
        out.push_str("\n\n");
    }

    // 每个 enum 都会 yield 一次 `enum_to_string_definition() + '\n'`，
    // 默认不开启 enum_to_string，所以等价于每个 enum 贡献一个空行
    for _ in &file.enums {
        out.push('\n');
    }

    // 字段描述符宽度检查（对应 generate_source 里的 max_field 逻辑）
    out.push_str(&render_field_width_check(file));

    // double 在部分平台（如 AVR）实际是 float，nanopb 会加一条静态断言
    let has_double = file
        .messages
        .iter()
        .flat_map(|m| m.fields.iter())
        .any(|f| f.ctype == "double");
    if has_double {
        out.push('\n');
        out.push_str("/* On some platforms (such as AVR), double is really float.\n");
        out.push_str(" * These are not directly supported by nanopb, but see example_avr_double.\n");
        out.push_str(" * To get rid of this error, remove any double fields from your .proto.\n");
        out.push_str(" */\n");
        out.push_str("PB_STATIC_ASSERT(sizeof(double) == 8, DOUBLE_MUST_BE_8_BYTES)\n");
    }

    out.push('\n');
    out.push_str("/* @@protoc_insertion_point(eof) */\n");

    out
}

/// `FieldMaxSize`：记录最大字段值，用于判断是否需要 PB_FIELD_16BIT/32BIT
#[derive(Debug, Default)]
struct FieldMaxSize {
    worst: u64,
    worst_field: String,
    checks: Vec<String>,
}

impl FieldMaxSize {
    fn new() -> Self {
        FieldMaxSize {
            worst: 0,
            worst_field: "undefined".to_string(),
            checks: Vec::new(),
        }
    }

    /// 对应 `FieldMaxSize.extend`
    fn extend(&mut self, other: FieldMaxSize) {
        let w = self.worst.max(other.worst);
        self.worst = w;
        if w == other.worst {
            self.worst_field = other.worst_field;
        }
        self.checks.extend(other.checks);
    }
}

/// 对应 `Field.largest_field_value`
fn largest_field_value(m: &MessageDef, f: &FieldDef) -> FieldMaxSize {
    let mut checks = Vec::new();

    if f.pbtype == "MESSAGE" && f.allocation == Allocation::Static {
        if f.rules == Rules::Repeated {
            checks.push(format!("pb_membersize({}, {}[0])", m.name(), f.name));
        } else {
            checks.push(format!("pb_membersize({}, {})", m.name(), f.name));
        }
    } else if f.pbtype == "BYTES"
        && f.allocation == Allocation::Static
        && f.max_size.unwrap_or(0) > 251
    {
        checks.push(format!("pb_membersize({}, {})", m.name(), f.name));
    }

    let mut worst = f.tag.max(0) as u64;
    if let Some(ms) = f.max_size {
        worst = worst.max(ms as u64);
    }
    if let Some(mc) = f.max_count {
        worst = worst.max(mc as u64);
    }

    FieldMaxSize {
        worst,
        worst_field: format!("{}.{}", m.name(), f.name),
        checks,
    }
}

/// 对应 `generate_source` 末尾的 PB_FIELD_16BIT / PB_FIELD_32BIT 检查
fn render_field_width_check(file: &ProtoFile) -> String {
    if file.messages.is_empty() {
        return String::new();
    }

    let mut max_field = FieldMaxSize::new();
    let mut msg_names: Vec<String> = Vec::new();

    for m in &file.messages {
        msg_names.push(m.name());
        for f in &m.fields {
            max_field.extend(largest_field_value(m, f));
        }
    }

    let worst = max_field.worst;
    let worst_field = &max_field.worst_field;
    let checks = &max_field.checks;

    if worst <= 255 && checks.is_empty() {
        return String::new();
    }

    let mut out = String::new();
    out.push_str("\n/* Check that field information fits in pb_field_t */\n");

    if worst > 65535 || !checks.is_empty() {
        out.push_str("#if !defined(PB_FIELD_32BIT)\n");
        if worst > 65535 {
            out.push_str(&format!(
                "#error Field descriptor for {} is too large. Define PB_FIELD_32BIT to fix this.\n",
                worst_field
            ));
        } else {
            let assertion = checks
                .iter()
                .map(|c| format!("{} < 65536", c))
                .collect::<Vec<_>>()
                .join(" && ");
            let msgs = msg_names.join("_");
            out.push_str(
                "/* If you get an error here, it means that you need to define PB_FIELD_32BIT\n",
            );
            out.push_str(" * compile-time option. You can do that in pb.h or on compiler command line.\n");
            out.push_str(" * \n");
            out.push_str(" * The reason you need to do this is that some of your messages contain tag\n");
            out.push_str(" * numbers or field sizes that are larger than what can fit in 8 or 16 bit\n");
            out.push_str(" * field descriptors.\n");
            out.push_str(" */\n");
            out.push_str(&format!(
                "PB_STATIC_ASSERT(({}), YOU_MUST_DEFINE_PB_FIELD_32BIT_FOR_MESSAGES_{})\n",
                assertion, msgs
            ));
        }
        out.push_str("#endif\n\n");
    }

    if worst < 65536 {
        out.push_str("#if !defined(PB_FIELD_16BIT) && !defined(PB_FIELD_32BIT)\n");
        if worst > 255 {
            out.push_str(&format!(
                "#error Field descriptor for {} is too large. Define PB_FIELD_16BIT to fix this.\n",
                worst_field
            ));
        } else {
            let assertion = checks
                .iter()
                .map(|c| format!("{} < 256", c))
                .collect::<Vec<_>>()
                .join(" && ");
            let msgs = msg_names.join("_");
            out.push_str(
                "/* If you get an error here, it means that you need to define PB_FIELD_16BIT\n",
            );
            out.push_str(" * compile-time option. You can do that in pb.h or on compiler command line.\n");
            out.push_str(" * \n");
            out.push_str(" * The reason you need to do this is that some of your messages contain tag\n");
            out.push_str(" * numbers or field sizes that are larger than what can fit in the default\n");
            out.push_str(" * 8 bit descriptors.\n");
            out.push_str(" */\n");
            out.push_str(&format!(
                "PB_STATIC_ASSERT(({}), YOU_MUST_DEFINE_PB_FIELD_16BIT_FOR_MESSAGES_{})\n",
                assertion, msgs
            ));
        }
        out.push_str("#endif\n\n");
    }

    out
}

