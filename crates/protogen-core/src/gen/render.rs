/// 对应 `Field.types()`
fn render_field_types(f: &FieldDef) -> String {
    if f.pbtype == "BYTES" && f.allocation == Allocation::Static {
        format!(
            "typedef PB_BYTES_ARRAY_T({}) {};\n",
            f.max_size.unwrap_or(0),
            f.ctype
        )
    } else {
        String::new()
    }
}

/// 对应 `Field.__str__`
fn render_field_decl(f: &FieldDef) -> Vec<String> {
    let mut lines = Vec::new();
    match f.allocation {
        Allocation::Pointer => {
            if f.rules == Rules::Repeated {
                lines.push(format!("    pb_size_t {}_count;", f.name));
            }
            if f.pbtype == "MESSAGE" {
                lines.push(format!("    struct _{} *{};", f.ctype, f.name));
            } else if f.pbtype == "FIXED_LENGTH_BYTES" {
                lines.push(format!(
                    "    {} (*{}){};",
                    f.ctype, f.name, f.array_decl
                ));
            } else if f.rules == Rules::Repeated
                && (f.pbtype == "STRING" || f.pbtype == "BYTES")
            {
                lines.push(format!("    {} **{};", f.ctype, f.name));
            } else {
                lines.push(format!("    {} *{};", f.ctype, f.name));
            }
        }
        Allocation::Callback => {
            lines.push(format!("    pb_callback_t {};", f.name));
        }
        Allocation::Static => {
            if f.rules == Rules::Optional {
                lines.push(format!("    bool has_{};", f.name));
            } else if f.rules == Rules::Repeated && !f.fixed_count {
                lines.push(format!("    pb_size_t {}_count;", f.name));
            }
            lines.push(format!("    {} {}{};", f.ctype, f.name, f.array_decl));
        }
    }
    lines
}

/// 对应 `Message.__str__`
fn render_message(m: &MessageDef) -> String {
    let name = m.name();
    let mut out = format!("typedef struct _{} {{\n", name);

    let ordered = m.ordered_fields();
    if ordered.is_empty() {
        out.push_str("    char dummy_field;");
    } else {
        let decls: Vec<String> = ordered
            .iter()
            .flat_map(|f| render_field_decl(f))
            .collect();
        out.push_str(&decls.join("\n"));
    }

    out.push_str(&format!("\n/* @@protoc_insertion_point(struct:{}) */", name));
    out.push_str(&format!("\n}} {};", name));
    out
}

/// 对应 `Field.get_initializer`
fn render_field_initializer(f: &FieldDef, null_init: bool, deps: &Deps) -> Option<String> {
    let inner = if f.pbtype == "MESSAGE" {
        let sub = f.submsgname.as_deref().unwrap_or(&f.ctype);
        if null_init {
            format!("{}_init_zero", sub)
        } else {
            format!("{}_init_default", sub)
        }
    } else if f.default.is_none() || null_init {
        match f.pbtype.as_str() {
            "STRING" => "\"\"".to_string(),
            "BYTES" => "{0, {0}}".to_string(),
            "FIXED_LENGTH_BYTES" => "{0}".to_string(),
            "ENUM" | "UENUM" => format!("_{}_MIN", f.ctype),
            _ => "0".to_string(),
        }
    } else {
        render_default_literal(f)
    };

    let outer = match f.allocation {
        Allocation::Static => {
            if f.rules == Rules::Repeated {
                let mc = f.max_count.unwrap_or(0);
                let items: Vec<String> = vec![inner.clone(); mc as usize];
                let mut s = String::new();
                if !f.fixed_count {
                    s.push_str("0, ");
                }
                s.push('{');
                s.push_str(&items.join(", "));
                s.push('}');
                s
            } else if f.rules == Rules::Optional {
                format!("false, {}", inner)
            } else {
                inner
            }
        }
        Allocation::Pointer => {
            if f.rules == Rules::Repeated {
                "0, NULL".to_string()
            } else {
                "NULL".to_string()
            }
        }
        Allocation::Callback => "{{NULL}, NULL}".to_string(),
    };

    let _ = deps;
    Some(outer)
}

/// 对应 `Field.get_initializer` 里 default 非空的分支
fn render_default_literal(f: &FieldDef) -> String {
    let d = f.default.clone().unwrap_or_default();
    match f.pbtype.as_str() {
        "STRING" => format!("\"{}\"", escape_c_string(&d)),
        "BYTES" => {
            let bytes = unescape_proto_bytes(&d);
            if bytes.is_empty() {
                "{0, {0}}".to_string()
            } else {
                let items: Vec<String> = bytes.iter().map(|b| format!("0x{:02x}", b)).collect();
                format!("{{{}, {{{}}}}}", bytes.len(), items.join(","))
            }
        }
        "FIXED_LENGTH_BYTES" => {
            let bytes = unescape_proto_bytes(&d);
            if bytes.is_empty() {
                "{0}".to_string()
            } else {
                let items: Vec<String> = bytes.iter().map(|b| format!("0x{:02x}", b)).collect();
                format!("{{{}}}", items.join(","))
            }
        }
        "FIXED32" | "UINT32" => format!("{}u", d),
        "FIXED64" | "UINT64" => format!("{}ull", d),
        "SFIXED64" | "INT64" => format!("{}ll", d),
        _ => d,
    }
}

fn escape_c_string(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn unescape_proto_bytes(s: &str) -> Vec<u8> {
    let mut out = Vec::new();
    let bytes = s.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'\\' && i + 1 < bytes.len() {
            match bytes[i + 1] {
                b'n' => {
                    out.push(b'\n');
                    i += 2;
                }
                b'r' => {
                    out.push(b'\r');
                    i += 2;
                }
                b't' => {
                    out.push(b'\t');
                    i += 2;
                }
                b'\\' => {
                    out.push(b'\\');
                    i += 2;
                }
                b'\'' => {
                    out.push(b'\'');
                    i += 2;
                }
                b'"' => {
                    out.push(b'"');
                    i += 2;
                }
                b'x' => {
                    let mut v = 0u8;
                    let mut n = 0;
                    let mut j = i + 2;
                    while j < bytes.len() && n < 2 {
                        match (bytes[j] as char).to_digit(16) {
                            Some(d) => {
                                v = v * 16 + d as u8;
                                n += 1;
                                j += 1;
                            }
                            None => break,
                        }
                    }
                    out.push(v);
                    i = j;
                }
                c => {
                    out.push(c);
                    i += 2;
                }
            }
        } else {
            out.push(bytes[i]);
            i += 1;
        }
    }
    out
}

/// 对应 `Message.get_initializer`
fn render_initializer(m: &MessageDef, null_init: bool, deps: &Deps) -> String {
    let ordered = m.ordered_fields();
    if ordered.is_empty() {
        return "{0}".to_string();
    }
    let parts: Vec<String> = ordered
        .iter()
        .filter_map(|f| render_field_initializer(f, null_init, deps))
        .collect();
    format!("{{{}}}", parts.join(", "))
}

/// 对应 `Field.default_decl(declaration_only=True)`
fn render_default_decl(m: &MessageDef, f: &FieldDef) -> Option<String> {
    f.default.as_ref()?;
    let array_decl = default_array_decl(f)?;
    Some(format!(
        "extern const {} {}_{}_default{};",
        f.ctype,
        m.name(),
        f.name,
        array_decl
    ))
}

/// 对应 `Field.default_decl(declaration_only=False)`
fn render_default_def(m: &MessageDef, f: &FieldDef) -> Option<String> {
    f.default.as_ref()?;
    let array_decl = default_array_decl(f)?;
    Some(format!(
        "const {} {}_{}_default{} = {};",
        f.ctype,
        m.name(),
        f.name,
        array_decl,
        render_default_literal(f)
    ))
}

/// 返回 `None` 表示该字段的默认值不生成（nanopb 里 return None 的分支）
fn default_array_decl(f: &FieldDef) -> Option<String> {
    match f.pbtype.as_str() {
        "STRING" => {
            if f.allocation != Allocation::Static {
                return None;
            }
            Some(format!("[{}]", f.max_size.unwrap_or(0)))
        }
        "BYTES" => {
            if f.allocation != Allocation::Static {
                return None;
            }
            Some(String::new())
        }
        "FIXED_LENGTH_BYTES" => {
            if f.allocation != Allocation::Static {
                return None;
            }
            Some(format!("[{}]", f.max_size.unwrap_or(0)))
        }
        _ => Some(String::new()),
    }
}

/// 对应 `Field.pb_field_t`
fn render_pb_field(f: &FieldDef, prev: Option<&str>, struct_name: &str) -> String {
    let mut s = String::from("    PB_FIELD(");
    s.push_str(&format!("{:>3}, ", f.tag));
    s.push_str(&format!("{:<8}, ", f.pbtype));
    s.push_str(&format!("{}, ", f.rules.as_str()));
    s.push_str(&format!("{:<8}, ", f.allocation.as_str()));
    match prev {
        None => s.push_str("FIRST, "),
        Some(_) => s.push_str("OTHER, "),
    }
    s.push_str(&format!("{}, ", struct_name));
    s.push_str(&format!("{}, ", f.name));
    s.push_str(&format!("{}, ", prev.unwrap_or(&f.name)));

    if f.pbtype == "MESSAGE" {
        s.push_str(&format!("&{}_fields)", f.submsgname.as_deref().unwrap_or("")));
    } else if f.default.is_none() {
        s.push_str("0)");
    } else if matches!(f.pbtype.as_str(), "BYTES" | "STRING" | "FIXED_LENGTH_BYTES")
        && f.allocation != Allocation::Static
    {
        // 任意长度的默认值不生成
        s.push_str("0)");
    } else {
        s.push_str(&format!("&{}_{}_default)", struct_name, f.name));
    }
    s
}

/// 对应 `Message.fields_definition`
fn render_fields_definition(m: &MessageDef) -> String {
    let name = m.name();
    let mut out = format!(
        "const pb_field_t {}_fields[{}] = {{\n",
        name,
        m.fields.len() + 1
    );
    let mut prev: Option<String> = None;
    for f in m.ordered_fields() {
        out.push_str(&render_pb_field(f, prev.as_deref(), &name));
        out.push_str(",\n");
        prev = Some(f.name.clone());
    }
    out.push_str("    PB_LAST_FIELD\n};");
    out
}

