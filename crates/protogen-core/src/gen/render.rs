/// 对应 `toposort2` + `sort_dependencies`：按依赖关系排序，同层按名字升序
fn sort_dependencies(messages: &[MessageDef]) -> Vec<&MessageDef> {
    let mut deps: HashMap<String, Vec<String>> = HashMap::new();
    let by_name: HashMap<String, &MessageDef> =
        messages.iter().map(|m| (m.name(), m)).collect();

    for m in messages {
        let mut d: Vec<String> = m
            .fields
            .iter()
            .filter(|f| f.allocation == Allocation::Static)
            .map(|f| f.ctype.clone())
            .collect();
        d.retain(|x| x != &m.name());
        d.sort();
        d.dedup();
        deps.insert(m.name(), d);
    }

    // 补齐外部依赖（不属于本文件的类型）
    let known: Vec<String> = deps.keys().cloned().collect();
    let mut extra: Vec<String> = Vec::new();
    for d in deps.values() {
        for x in d {
            if !known.contains(x) {
                extra.push(x.clone());
            }
        }
    }
    for e in extra {
        deps.entry(e).or_default();
    }

    let mut result = Vec::new();
    loop {
        let mut ordered: Vec<String> = deps
            .iter()
            .filter(|(_, d)| d.is_empty())
            .map(|(k, _)| k.clone())
            .collect();
        if ordered.is_empty() {
            break;
        }
        ordered.sort();
        for name in &ordered {
            if let Some(m) = by_name.get(name) {
                result.push(*m);
            }
        }
        let ordered_set: std::collections::HashSet<String> = ordered.into_iter().collect();
        deps = deps
            .into_iter()
            .filter(|(k, _)| !ordered_set.contains(k))
            .map(|(k, d)| {
                let nd: Vec<String> = d
                    .into_iter()
                    .filter(|x| !ordered_set.contains(x))
                    .collect();
                (k, nd)
            })
            .collect();
    }

    result
}

/// 对应 `Field.encoded_size` + `Message.encoded_size`，返回可静态确定的长度
fn message_encoded_size(m: &MessageDef, deps: &Deps) -> Option<u32> {
    let mut total = 0u32;
    for f in &m.fields {
        total += field_encoded_size(f, deps)?;
    }
    Some(total)
}

fn field_encoded_size(f: &FieldDef, deps: &Deps) -> Option<u32> {
    if f.allocation != Allocation::Static {
        return None;
    }

    let mut size = match f.pbtype.as_str() {
        "MESSAGE" => {
            let sub = f.submsgname.as_deref()?;
            let submsg = deps.messages.get(sub)?;
            let inner = message_encoded_size(submsg, deps)?;
            inner + crate::parse::varint_max_size(inner as u64)
        }
        "ENUM" | "UENUM" => {
            let e = deps.enums.get(&f.ctype)?;
            let max = e
                .values
                .iter()
                .map(|v| crate::parse::varint_max_size(v.number.unsigned_abs() as u64))
                .max()
                .unwrap_or(1);
            max
        }
        _ => f.enc_size?,
    };

    size += crate::parse::varint_max_size((f.tag as u64) << 3);

    if f.rules == Rules::Repeated {
        let mc = f.max_count?;
        size *= mc;
        if mc == 1 {
            size += 1;
        }
    }

    Some(size)
}
