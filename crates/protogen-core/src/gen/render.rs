//! nanopb 0.3.9.1 风格的 C 代码渲染（不含注释注入）。
//!
//! 每个函数都能在 `nanopb_generator.py` 里找到对应实现，注释里标了函数名。

use std::collections::HashMap;

use crate::model::*;

#[derive(Debug, Clone)]
pub struct GenOptions {
    pub no_timestamp: bool,
    pub nanopb_version: String,
    /// 生成时间字符串（`time.asctime()` 的等价物），no_timestamp 为 true 时忽略
    pub timestamp: String,
}

impl Default for GenOptions {
    fn default() -> Self {
        GenOptions {
            no_timestamp: true,
            nanopb_version: "nanopb-0.3.9.1".to_string(),
            timestamp: String::new(),
        }
    }
}

#[derive(Debug, Clone, Default)]
pub struct GenOutput {
    pub header: String,
    pub source: String,
}

/// 对应 `make_identifier`
fn make_identifier(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect()
}

/// 依赖集合：消息名 → 消息，枚举名 → 枚举
struct Deps<'a> {
    messages: HashMap<String, &'a MessageDef>,
    enums: HashMap<String, &'a EnumDef>,
}

impl<'a> Deps<'a> {
    fn new(file: &'a ProtoFile) -> Self {
        let mut messages = HashMap::new();
        let mut enums = HashMap::new();
        for m in &file.messages {
            messages.insert(m.name(), m);
        }
        for e in &file.enums {
            enums.insert(e.names.as_str(), e);
        }
        Deps { messages, enums }
    }
}

pub fn generate(file: &ProtoFile, opts: &GenOptions) -> GenOutput {
    let deps = Deps::new(file);
    GenOutput {
        header: gen_header(file, opts, &deps),
        source: gen_source(file, opts),
    }
}

// ---------------------------------------------------------------------------
// Header
// ---------------------------------------------------------------------------

fn gen_header(file: &ProtoFile, opts: &GenOptions, deps: &Deps) -> String {
    let mut out = String::new();

    out.push_str("/* Automatically generated nanopb header */\n");
    if opts.no_timestamp {
        out.push_str(&format!("/* Generated by {} */\n\n", opts.nanopb_version));
    } else {
        out.push_str(&format!(
            "/* Generated by {} at {}. */\n\n",
            opts.nanopb_version, opts.timestamp
        ));
    }

    // nanopb 的 headername 是完整文件名（含 .pb.h），symbol 由它生成
    let headername = format!("{}.pb.h", file.base_name);
    let symbol = match &file.package {
        Some(p) => make_identifier(&format!("{}_{}", p, headername)),
        None => make_identifier(&headername),
    };
    out.push_str(&format!("#ifndef PB_{}_INCLUDED\n", symbol));
    out.push_str(&format!("#define PB_{}_INCLUDED\n", symbol));
    out.push_str("#include <pb.h>\n\n");

    for inc in &file.dependencies {
        out.push_str(&format!("#include \"{}.pb.h\"\n", inc));
    }
    if !file.dependencies.is_empty() {
        out.push('\n');
    }

    out.push_str("/* @@protoc_insertion_point(includes) */\n");
    out.push_str("#if PB_PROTO_HEADER_VERSION != 30\n");
    out.push_str("#error Regenerate this file with the current version of nanopb generator.\n");
    out.push_str("#endif\n\n");
    out.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");

    if !file.enums.is_empty() {
        out.push_str("/* Enum definitions */\n");
        for e in &file.enums {
            out.push_str(&render_enum(e));
            out.push_str("\n\n");
        }
    }

    if !file.messages.is_empty() {
        out.push_str("/* Struct definitions */\n");
        for m in sort_dependencies(&file.messages) {
            for f in &m.fields {
                out.push_str(&render_field_types(f));
            }
            out.push_str(&render_message(m));
            out.push_str("\n\n");
        }

        out.push_str("/* Default values for struct fields */\n");
        for m in &file.messages {
            for f in &m.fields {
                if let Some(d) = render_default_decl(m, f) {
                    out.push_str(&d);
                    out.push('\n');
                }
            }
        }
        out.push('\n');

        out.push_str("/* Initializer values for message structs */\n");
        for m in &file.messages {
            out.push_str(&format!(
                "#define {:<40} {}\n",
                format!("{}_init_default", m.name()),
                render_initializer(m, false, deps)
            ));
        }
        for m in &file.messages {
            out.push_str(&format!(
                "#define {:<40} {}\n",
                format!("{}_init_zero", m.name()),
                render_initializer(m, true, deps)
            ));
        }
        out.push('\n');

        out.push_str("/* Field tags (for use in manual encoding/decoding) */\n");
        for m in sort_dependencies(&file.messages) {
            for f in &m.fields {
                out.push_str(&format!(
                    "#define {:<40} {}\n",
                    format!("{}_{}_tag", m.name(), f.name),
                    f.tag
                ));
            }
        }
        out.push('\n');

        out.push_str("/* Struct field encoding specification for nanopb */\n");
        for m in &file.messages {
            out.push_str(&format!(
                "extern const pb_field_t {}_fields[{}];\n",
                m.name(),
                m.fields.len() + 1
            ));
        }
        out.push('\n');

        out.push_str("/* Maximum encoded size of messages (where known) */\n");
        for m in &file.messages {
            let id = format!("{}_size", m.name());
            match message_encoded_size(m, deps) {
                Some(v) => out.push_str(&format!("#define {:<40} {}\n", id, v)),
                None => out.push_str(&format!("/* {} depends on runtime parameters */\n", id)),
            }
        }
        out.push('\n');

        out.push_str("/* Message IDs (where set with \"msgid\" option) */\n");
        out.push_str("#ifdef PB_MSGID\n");
        for m in &file.messages {
            if let Some(id) = m.msgid {
                out.push_str(&format!("#define PB_MSG_{} {}\n", id, m.name()));
            }
        }
        out.push('\n');

        let sym = make_identifier(&file.base_name);
        out.push_str(&format!("#define {}_MESSAGES \\\n", sym));
        for m in &file.messages {
            if let Some(id) = m.msgid {
                let size = message_encoded_size(m, deps)
                    .map(|v| v.to_string())
                    .unwrap_or_else(|| "-1".to_string());
                out.push_str(&format!("\tPB_MSG({},{},{}) \\\n", id, size, m.name()));
            }
        }
        out.push('\n');

        for m in &file.messages {
            if let Some(id) = m.msgid {
                out.push_str(&format!("#define {}_msgid {}\n", m.name(), id));
            }
        }
        out.push('\n');
        out.push_str("#endif\n\n");
    }

    out.push_str("#ifdef __cplusplus\n} /* extern \"C\" */\n#endif\n");
    out.push_str("/* @@protoc_insertion_point(eof) */\n");
    out.push_str("\n#endif\n");

    out
}

