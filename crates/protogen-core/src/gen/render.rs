/// 对应 `Enum.__str__`
fn render_enum(e: &EnumDef) -> String {
    let names = e.names.as_str();
    let mut out = format!("typedef enum _{} {{\n", names);
    let body: Vec<String> = e
        .values
        .iter()
        .map(|v| format!("    {} = {}", v.name, v.number))
        .collect();
    out.push_str(&body.join(",\n"));
    out.push_str(&format!("\n}} {};", names));

    if let (Some(first), Some(last)) = (e.values.first(), e.values.last()) {
        out.push_str(&format!("\n#define _{}_MIN {}", names, first.name));
        out.push_str(&format!("\n#define _{}_MAX {}", names, last.name));
        out.push_str(&format!(
            "\n#define _{}_ARRAYSIZE (({})({}+1))",
            names, names, last.name
        ));
    }
    out
}

